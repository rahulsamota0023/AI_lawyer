def _fmt_date(iso):
    if not iso:
        return None
    return datetime.strptime(iso, "%Y-%m-%d").strftime("%d %B %Y")


def _inr(n):
    s = f"{int(n):,}"  # western grouping first, then convert to Indian grouping
    n = int(n)
    if n < 1000:
        return str(n)
    head, tail = str(n)[:-3], str(n)[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join(parts + [tail])


def _ph(label):
    return f"[FILL: {label}]"


def _v(case, key, label, fmt=None):
    v = case.get(key)
    if not v:
        return _ph(label)
    return fmt(v) if fmt else str(v)


def _proof_list(case):
    p = [x for x in case.get("proof", []) if x.lower() != "none"]
    return "\n".join(f"   - {x}" for x in p) if p else "   - [FILL: list the documents/chats you hold]"


HEADER = ("DRAFT - generated by an AI tool from the facts you gave. Check every detail, fill the [FILL: ...] gaps, and "
          "consider having a lawyer review it before you send it. This is not legal advice.\n")


def _party_block(case, today):
    return (f"Date: {_fmt_date(today.isoformat())}\n"
            "Sent by: Registered Post AD / Speed Post and email (keep the receipts and delivery proof)\n\n"
            f"To,\n{_v(case, 'other_party_name', 'name of the other party')}\n{_v(case, 'other_party_address', 'their address')}\n\n"
            f"From,\n{_v(case, 'user_name', 'your name')}\n{_v(case, 'user_address', 'your address')}\n")


def tenancy_notice(case, today):
    amt = _v(case, "amount", "deposit amount", lambda x: f"Rs {_inr(x)}")
    mta = ""
    if case.get("mta_applies"):
        mta = ("\n6. I am advised that under Section 11 of the Model Tenancy Act, 2021, as applicable in your State, a security deposit "
               "is refundable when vacant possession is taken back, after lawful deductions.\n")
    body = f"""{HEADER}
{_party_block(case, today)}
Subject: Notice demanding refund of security deposit of {amt}

Sir/Madam,

1. I was your tenant at {_v(case, 'property_address', 'property address')}. {('The monthly rent was Rs ' + _inr(case['monthly_rent']) + '. ') if case.get('monthly_rent') else ''}
2. I paid you a refundable security deposit of {amt}{(' on ' + _fmt_date(case['deposit_paid_date'])) if case.get('deposit_paid_date') else ''}.
3. I vacated the premises and handed over possession on {_v(case, 'vacated_date', 'date you vacated', _fmt_date)}.
4. {case.get('what_happened') or _ph('what happened about the refund')}
5. Despite my requests, you have not refunded the deposit{(' and have claimed deductions: ' + case['deductions_claimed']) if case.get('deductions_claimed') else ''}. I dispute any deduction not supported by written proof.
{mta}
I therefore call upon you to pay {amt} to me within [15] days of receiving this notice, together with reasonable interest from the date I vacated. If you fail to do so, I will be compelled to take legal action for recovery, including interest and costs, entirely at your risk and cost.

Documents I hold:
{_proof_list(case)}

Yours faithfully,
{_v(case, 'user_name', 'your name')}
Signature: ____________    Date: ____________
"""
    return {"title": "Legal notice: refund of security deposit", "body": body}


