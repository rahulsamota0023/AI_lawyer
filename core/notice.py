BUILDERS = {
    "tenancy": [tenancy_notice],
    "wages": [wages_notice],
    "consumer": [consumer_notice, consumer_complaint_outline],
}


FREE_TEXT = ("what_happened", "deductions_claimed", "product_or_service")


def sanitize(case):
    """Free-text fields were written by the model/user and are pasted into legal papers: run them through the same
    citation checker so no unverified section or case name can reach a notice. Returns (safe_case, removed_report)."""
    safe, report = dict(case), []
    for k in FREE_TEXT:
        if safe.get(k):
            safe[k], rep = G.check_reply(safe[k])
            report += rep
    safe["proof"] = [G.check_reply(x)[0] for x in case.get("proof", [])]
    return safe, report


def build_documents(case, today: date = None):
    today = today or date.today()
    safe, report = sanitize(case)
    docs = [b(safe, today) for b in BUILDERS.get(case.get("category"), [])]
    for d in docs:
        d["placeholders"] = d["body"].count("[FILL:")
        d["removed_citations"] = report
    return docs
